#!/usr/bin/env python3
"""Extract the original's objects ("things") as they are on the tape.

    .venv/bin/python tools/mkobjects.py [--snap build/ce2.z80]

From the snapshot taken as the tape finishes loading (nothing has run on
the tables yet). Writes, committed (the build never runs this):
    src/data/things.bin     the thing table &6600-&69FF: room (bit 7 = not
                            in the world), row, column, type, 256 each
    src/data/thinginit.bin  rooms, rows, columns of things 0-&28 (their
                            start, restored every egg)
    src/data/thingtypes.bin the 67 types &6A00-&6AC8 as three tables, 67
                            inks, 67 graphics (renumbered: below), 67 kinds
    src/data/visits.bin     the room-visit bonus &A380-&A3F8 (room 0-120)
    src/data/objgfx.bin     the object images &6FD0-&74B7, each a column
                            at a time, packed as the monsters' are
                            (tools/mkgfx.py)
    src/data/objects.6502   the graphic pointers (&8A98, 73), relocated to
                            `objgfx`, as low and high bytes; without the
                            nine the original keeps twice (below)
See docs/research/objects.md.

The original's pointers &00-&07 and &0E are the boat's (the tape's types
0-8 have them), and &37-&3F the boat's again, for &9B08's base + t. The
port keeps one copy: the boat's nine at 0-8 (&0E moved to 8, &08-&0D to
9-14), the original's &40-&48 at &37-&3F, and the types' graphics and the
toys' bases renumbered to match, so every type has the same picture.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from zx import Spectrum  # noqa: E402
from mkgfx import columns, pack, unpack  # noqa: E402

THINGS, TYPES, TYPES_END = 0x6600, 0x6A00, 0x6AC9
VISITS, VISITS_END = 0xA380, 0xA3F9
OBJGFX, OBJGFX_END = 0x6FD0, 0x74B8
OBJ_POINTERS, OBJ_POINTER_COUNT = 0x8A98, 73


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--snap", default="build/ce2.z80")
    ap.add_argument("--out", default="src/data")
    args = ap.parse_args()
    m = Spectrum(args.snap).mem
    word = lambda a: m[a] | m[a + 1] << 8
    out = lambda name, a, b: open(f"{args.out}/{name}", "wb").write(bytes(m[a:b]))
    out("things.bin", THINGS, THINGS + 1024)
    # Where the 41 portable things start each egg (the original copies these
    # to &5B00 at start-up and back at every egg): rooms, rows, columns.
    open(f"{args.out}/thinginit.bin", "wb").write(
        bytes(m[THINGS:THINGS + 41] + m[THINGS + 256:THINGS + 256 + 41] + m[THINGS + 512:THINGS + 512 + 41]))
    out("visits.bin", VISITS, VISITS_END)
    # The images packed as the monsters' are (tools/mkgfx.py): a column at
    # a time, without their empty top and bottom lines, a mirror image as
    # a stub.
    pointers = [word(OBJ_POINTERS + 2 * i) for i in range(OBJ_POINTER_COUNT)]
    assert all(OBJGFX <= p < OBJGFX_END for p in pointers)
    blob, where = pack(m, pointers)
    for p in set(pointers):
        assert unpack(blob, where[p]) == columns(m, p), hex(p)
    open(f"{args.out}/objgfx.bin", "wb").write(blob)
    # One copy of the boat (the docstring): the port's order of the
    # original's graphics, and each one's new number.
    boat = list(range(0x37, 0x40))
    assert [pointers[g] for g in boat] == [pointers[g] for g in [*range(8), 0x0E]]
    order = [*range(8), 0x0E, *range(8, 0x0E), *range(0x0F, 0x37), *range(0x40, OBJ_POINTER_COUNT)]
    renumber = {g: i for i, g in enumerate(order)}
    renumber.update({g: renumber[b] for g, b in zip(boat, [*range(8), 0x0E])})
    # The types as three tables (ink, graphic, kind): a type indexes each.
    types = bytes(m[TYPES:TYPES_END])
    gfx = bytes(renumber[g] for g in types[1::3])
    open(f"{args.out}/thingtypes.bin", "wb").write(types[0::3] + gfx + types[2::3])
    # Each toy's first graphic, by egg AND 3 (&9B08's base: &1C + 9 x the
    # egg's toy, 1-4, the jet's 4 for eggs 4, 8 ...).
    toys = [renumber[0x1C + 9 * (((e - 1) & 3) + 1)] for e in range(4)]
    lines = [
        "\\ Generated by tools/mkobjects.py from the original: do not edit.",
        "",
        "\\ The object graphics (&8A98, renumbered: tools/mkobjects.py): a type's",
        "\\ graphic indexes these, the headers' low and high bytes.",
    ]
    for half in ("lo", "hi"):
        lines.append(f".object_{half}")
        for k in range(0, len(order), 4):
            lines.append("    EQUB " + ", ".join(
                f"{half.upper()}(objgfx + &{where[pointers[g]]:04X})" for g in order[k:k + 4]))
    lines += [
        "",
        "\\ Each toy's first graphic (egg_init), by egg AND 3: the jet for eggs 4,",
        "\\ 8 ..., the motorbike for 1, 5 ..., the car, the boat.",
        ".toy_frames",
        "    EQUB " + ", ".join(f"&{t:02X}" for t in toys),
    ]
    open(f"{args.out}/objects.6502", "w").write("\n".join(lines) + "\n")
    print("things: 1024, types:", TYPES_END - TYPES, "visits:", VISITS_END - VISITS,
          "graphics:", len(blob), f"(the original's {OBJGFX_END - OBJGFX})")


if __name__ == "__main__":
    main()
